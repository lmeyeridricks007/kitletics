import { writeFileSync, mkdirSync, readFileSync } from "node:fs";
import { reviewMergeDecisions } from "@/content/reviews";
import { getLaunchEligibility, isIndexableEligibility } from "@/domain/launch";
import { assessConsumerCopyQuality } from "@/lib/review/consumer-copy-quality";
import { containsPublicContentCorruption } from "@/lib/review/public-content-corruption";
import { containsMachineTemplateCopy } from "@/lib/review/consumer-copy-quality";

const PROD = { isDev: false as const };

function collect() {
  const published = reviewMergeDecisions.filter((d) => d.review.status === "published");
  const reasons: Record<string, number> = {};
  let ok = 0;
  let fail = 0;
  let machine = 0;
  let corrupt = 0;
  let indexable = 0;
  let indexableMachine = 0;
  let indexableCorrupt = 0;
  let indexableUnusable = 0;
  const bySource: Record<string, number> = {};
  const failSlugs: string[] = [];

  for (const d of published) {
    bySource[d.source] = (bySource[d.source] ?? 0) + 1;
    const qa = assessConsumerCopyQuality(d.review);
    const elig = getLaunchEligibility({ kind: "review", entity: d.review }, PROD);
    const indexableNow = isIndexableEligibility(elig);
    if (indexableNow) indexable += 1;
    if (containsPublicContentCorruption(d.review)) {
      corrupt += 1;
      if (indexableNow) indexableCorrupt += 1;
    }
    if (containsMachineTemplateCopy(d.review)) {
      machine += 1;
      if (indexableNow) indexableMachine += 1;
    }
    if (!qa.ok) {
      fail += 1;
      failSlugs.push(d.review.slug);
      for (const r of qa.reasons) reasons[r] = (reasons[r] ?? 0) + 1;
      if (indexableNow) indexableUnusable += 1;
    } else {
      ok += 1;
    }
  }

  return {
    published: published.length,
    ok,
    fail,
    machine,
    corrupt,
    indexable,
    indexableMachine,
    indexableCorrupt,
    indexableUnusable,
    reasons,
    bySource,
    failSlugs,
  };
}

const after = collect();
let before: {
  publishedKept?: number;
  publishedFail?: number;
  machineTemplate?: number;
  reasons?: Record<string, number>;
} = {};
let rebuildCount = 0;
let heldCount = 0;
try {
  const stats = JSON.parse(
    readFileSync("docs/remediation/data/review-editorial-rebuild-stats.json", "utf8"),
  ) as {
    before?: typeof before;
    rebuilt?: number;
    held?: number;
    rebuiltSlugs?: string[];
    heldSlugs?: string[];
    keptSlugs?: string[];
  };
  before = stats.before ?? {};
  rebuildCount = stats.rebuilt ?? 0;
  heldCount = stats.held ?? 0;
  mkdirSync("docs/remediation", { recursive: true });
  const rebuiltSlugs = (stats.rebuiltSlugs ?? []).slice().sort();
  const heldSlugs = (stats.heldSlugs ?? []).slice().sort();

  const md = `# Review editorial rebuild

This workstream repairs reviews that had **no acceptable consumer editorial source**.
It does **not** generate section images. It does **not** declare the overall site fixed.

## Philosophy

Semantic usefulness is the quality target. Natural overlap such as
“daily trainer”, “soft cushioning”, or “8 mm drop” is acceptable when
factually necessary. Uniqueness stamps, SKU fingerprints, artificial n-grams,
and sentence shuffling are not.

## What changed

- Detector: \`src/lib/review/consumer-copy-quality.ts\` (machine templates + analysis/decision gates)
- Generator: \`src/domain/review-agent/unique-expert-research.ts\` writes consumer verdict, Buy/Skip, methodology, and performance analysis
- Page enricher no longer preserves uniqueness methodology dumps or expands concise consumer bullets into templates
- Merge: \`editorial_rebuild\` (rank 25) wins when handwritten / P62 copy is unusable
- Publication: machine template, missing analysis, and unreadable decision bullets are BLOCKED → not indexable
- Overlay: \`src/content/reviews-editorial-rebuild.json\` (generated by \`scripts/review-editorial-rebuild.ts\`)

## Before (baseline, ignoring rebuild overlay)

| Metric | Count |
| --- | ---: |
| Published reviews that already passed consumer QA | ${before.publishedKept ?? "—"} |
| Published reviews that failed consumer QA | ${before.publishedFail ?? "—"} |
| Machine-template failures | ${before.machineTemplate ?? "—"} |
| Missing product-specific analysis | ${before.reasons?.MISSING_PRODUCT_SPECIFIC_ANALYSIS ?? "—"} |
| Unreadable decision bullets | ${before.reasons?.DECISION_BULLETS_UNREADABLE ?? "—"} |

## Rebuild actions

| Metric | Count |
| --- | ---: |
| Reviews rebuilt into overlay | ${rebuildCount} |
| Held (synthesis could not pass QA) | ${heldCount} |

## After (winning public reviews)

| Metric | Count |
| --- | ---: |
| Published reviews | ${after.published} |
| Passing consumer QA | ${after.ok} |
| Remaining consumer QA failures | ${after.fail} |
| Machine-template winning reviews | ${after.machine} |
| Token-corruption winning reviews | ${after.corrupt} |
| Indexable reviews | ${after.indexable} |
| Indexable machine-template reviews | ${after.indexableMachine} |
| Indexable corrupted reviews | ${after.indexableCorrupt} |
| Indexable unusable editorial | ${after.indexableUnusable} |

### Winning source mix

| Source | Winning reviews |
| --- | ---: |
${Object.entries(after.bySource)
  .sort((a, b) => b[1] - a[1])
  .map(([k, v]) => `| ${k} | ${v} |`)
  .join("\n")}

## Remaining stored analysis misses

These **${after.fail} handwritten** reviews still fail the stored-seed analysis bar
(short editorial seeds, often 20–40 words per section). They are **not**
machine-template and **not** token-corrupted.

Page-time enrichment still expands them (Vomero 18 lands around 3,800 words
and LAUNCH_READY / INDEXABLE). An overlay record exists for several of
these slugs, but handwritten copy wins because the source is an acceptable
editorial seed rather than uniqueness-era template copy.

${after.failSlugs.map((s) => `- \`${s}\``).join("\n")}

## Rebuilt slugs

<details>
<summary>${rebuiltSlugs.length} slugs</summary>

${rebuiltSlugs.map((s) => `- \`${s}\``).join("\n")}

</details>

${
  heldSlugs.length
    ? `## Held slugs

${heldSlugs.map((s) => `- \`${s}\``).join("\n")}`
    : ""
}

## Gates that must stay true

- PUBLIC/INDEXABLE CORRUPTED REVIEWS = 0
- PUBLIC/INDEXABLE MACHINE-TEMPLATE REVIEWS = 0
- No review is indexable unless corruption = 0, machine template = 0, required evidence exists, decision bullets are readable, and the review has meaningful product-specific analysis
`;

  writeFileSync("docs/remediation/REVIEW-EDITORIAL-REBUILD.md", md);
} catch (err) {
  console.error(err);
}

console.log(
  JSON.stringify(
    {
      before,
      rebuilt: rebuildCount,
      held: heldCount,
      after,
    },
    null,
    2,
  ),
);
