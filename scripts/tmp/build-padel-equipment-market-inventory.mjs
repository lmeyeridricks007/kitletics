function csvEscape(v) {
  const s = String(v ?? "");
  if (/[",\n]/.test(s)) return `"${s.replace(/"/g, '""')}"`;
  return s;
}

function row(r) {
  const key = `${r.brand}|${r.model}`.toLowerCase();
  const existingId = EXISTING[key] ?? "";
  const existing = existingId ? "yes" : "no";
  return [
    r.category,
    r.subcategory,
    r.brand,
    r.product,
    r.model,
    r.generation ?? "",
    r.gender ?? "unisex",
    r.variant ?? "",
    r.manufacturer_url ?? "",
    r.manufacturer_status ?? "current",
    r.retailer_urls ?? "",
    r.NL_available ?? "unknown",
    r.EU_available ?? "yes",
    r.current_status ?? "CURRENT",
    existing,
    existingId,
    r.evidence ?? "",
    r.research_status ?? "verified",
  ]
    .map(csvEscape)
    .join(",");
}

