/**
 * Import filled affiliate URLs from kitletics-products-affiliate-urls.xlsm
 * into src/content/offers-affiliate-urls.ts (overlay merged at offer materialize).
 *
 *   npm run offers:import-affiliate
 *
 * Accepts only https://amzn.to/… short links. Skips Google Ads trackers and
 * non-URL cells. Re-run after updating the spreadsheet.
 */
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { spawnSync } from "node:child_process";

const SHEET = resolve(process.cwd(), "kitletics-products-affiliate-urls.xlsm");
const OUT = resolve(process.cwd(), "src/content/offers-affiliate-urls.ts");

type Parsed = {
  rows: Array<{ id: string; slug: string; affiliateUrl: string }>;
  skipped: Record<string, number>;
};

function parseSheet(): Parsed {
  const py = `
import json, openpyxl
from urllib.parse import urlparse
wb = openpyxl.load_workbook(${JSON.stringify(SHEET)}, data_only=True)
ws = wb["Products"]
rows = list(ws.iter_rows(values_only=True))
headers = [str(c or "") for c in rows[0]]
idx = {h: i for i, h in enumerate(headers)}
out = []
skipped = {"empty": 0, "google": 0, "invalid": 0, "other_host": 0}
for r in rows[1:]:
    if not r or not r[idx.get("id", 0)]:
        continue
    pid = str(r[idx["id"]]).strip()
    slug = str(r[idx["slug"]] or "").strip()
    url = str(r[idx["affiliateUrl"]] or "").strip()
    if not url:
        skipped["empty"] += 1
        continue
    if not url.startswith("http"):
        skipped["invalid"] += 1
        continue
    host = urlparse(url).netloc.lower()
    if "google." in host:
        skipped["google"] += 1
        continue
    if host != "amzn.to":
        skipped["other_host"] += 1
        continue
    out.append({"id": pid, "slug": slug, "affiliateUrl": url.split("#")[0]})
print(json.dumps({"rows": out, "skipped": skipped}))
`;
  const res = spawnSync("python3", ["-c", py], { encoding: "utf8" });
  if (res.status !== 0) {
    throw new Error(`Failed to parse xlsm:\n${res.stderr || res.stdout}`);
  }
  return JSON.parse(res.stdout) as Parsed;
}

function main() {
  const parsed = parseSheet();
  const byId = new Map<string, string>();
  for (const row of parsed.rows) {
    byId.set(row.id, row.affiliateUrl);
  }

  const now = new Date().toISOString();
  const entries = [...byId.entries()].sort(([a], [b]) => a.localeCompare(b));
  const body = entries
    .map(([id, url]) => `  ${JSON.stringify(id)}: ${JSON.stringify(url)},`)
    .join("\n");

  const file = `/**
 * AUTO-GENERATED by scripts/import-affiliate-urls.ts — do not hand-edit.
 * Source: kitletics-products-affiliate-urls.xlsm
 * Generated: ${now}
 * Products with amzn.to links: ${entries.length}
 * Skipped: ${JSON.stringify(parsed.skipped)}
 *
 * Re-run: npm run offers:import-affiliate
 */
export const PRODUCT_AFFILIATE_URLS: Readonly<Record<string, string>> = {
${body}
};
`;

  writeFileSync(OUT, file, "utf8");
  console.log(`Wrote ${entries.length} amzn.to links → ${OUT}`);
  console.log("Skipped", parsed.skipped);
}

main();
